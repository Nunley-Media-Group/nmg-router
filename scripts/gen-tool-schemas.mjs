// Generates src/tools/builtin-schemas.ts from the tool declarations the installed
// Claude Code writes under .claude-plugin/types/ (BuiltinToolInputs). Run it with
// `npm run tools:schemas` after `npm run types:sync`. The output is checked in,
// and a test regenerates it in memory to catch a stale registry.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const toolDeclarations = join(root, ".claude-plugin", "types", "claude-code-tools", "index.d.ts");
const versionDeclarations = join(root, ".claude-plugin", "types", "claude-code", "index.d.ts");
const output = join(root, "src", "tools", "builtin-schemas.ts");

const VERSION_MARKER = /Written by Claude Code (\d+\.\d+\.\d+)\./;

// The Claude Code version named in the declarations' first line.
export function declarationVersion(text) {
  const match = VERSION_MARKER.exec(text.split("\n", 1)[0] ?? "");
  if (match === null) throw new Error("the Claude Code declarations do not name their version");
  return match[1];
}

function findInterface(node, name) {
  if (ts.isInterfaceDeclaration(node) && node.name.text === name) return node;
  return ts.forEachChild(node, (child) => findInterface(child, name));
}

function nameOf(name) {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name)) return name.text;
  return undefined;
}

// JSDoc text on a declaration, trimmed; undefined when there is none.
function descriptionOf(node) {
  const text = ts
    .getJSDocCommentsAndTags(node)
    .filter(ts.isJSDoc)
    .map((doc) => (typeof doc.comment === "string" ? doc.comment.trim() : ""))
    .filter((comment) => comment !== "")
    .join(" ");
  return text === "" ? undefined : text;
}

function isNullish(node) {
  return node.kind === ts.SyntaxKind.UndefinedKeyword || (ts.isLiteralTypeNode(node) && node.literal.kind === ts.SyntaxKind.NullKeyword);
}

function isStringLiteral(node) {
  return ts.isLiteralTypeNode(node) && ts.isStringLiteral(node.literal);
}

function withDescription(schema, description) {
  return description === undefined ? schema : { ...schema, description };
}

function objectSchema(node, path, warn) {
  const properties = {};
  const required = [];
  for (const member of node.members) {
    const key = ts.isPropertySignature(member) ? nameOf(member.name) : undefined;
    if (key === undefined || member.type === undefined) {
      warn(`gen-tool-schemas: ${path} has a member that is not a named property; it is left out`);
      continue;
    }
    properties[key] = withDescription(schemaOf(member.type, `${path}.${key}`, warn), descriptionOf(member));
    if (member.questionToken === undefined) required.push(key);
  }
  return {
    type: "object",
    properties,
    ...(required.length > 0 ? { required } : {}),
    additionalProperties: false,
  };
}

// The JSON Schema for one type node. A construct this maps to nothing becomes `{}`
// and is named on the warning channel.
function schemaOf(node, path, warn) {
  if (ts.isParenthesizedTypeNode(node)) return schemaOf(node.type, path, warn);
  if (node.kind === ts.SyntaxKind.StringKeyword) return { type: "string" };
  if (node.kind === ts.SyntaxKind.NumberKeyword) return { type: "number" };
  if (node.kind === ts.SyntaxKind.BooleanKeyword) return { type: "boolean" };
  if (isStringLiteral(node)) return { type: "string", enum: [node.literal.text] };
  if (ts.isUnionTypeNode(node)) {
    const members = node.types.filter((member) => !isNullish(member));
    if (members.length === 1) return schemaOf(members[0], path, warn);
    if (members.length > 0 && members.every(isStringLiteral)) {
      return { type: "string", enum: members.map((member) => member.literal.text) };
    }
  }
  if (ts.isArrayTypeNode(node)) return { type: "array", items: schemaOf(node.elementType, path, warn) };
  if (ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName)) {
    const args = node.typeArguments ?? [];
    if (node.typeName.text === "Array" && args.length === 1) {
      return { type: "array", items: schemaOf(args[0], path, warn) };
    }
    if (node.typeName.text === "Record" && args.length === 2) {
      return { type: "object", additionalProperties: schemaOf(args[1], path, warn) };
    }
  }
  if (ts.isTypeLiteralNode(node)) return objectSchema(node, path, warn);
  warn(`gen-tool-schemas: ${path} has an unsupported type (${ts.SyntaxKind[node.kind]}); its schema is {}`);
  return {};
}

function render(tools, version) {
  return [
    `// Generated by scripts/gen-tool-schemas.mjs from the tool declarations of Claude Code ${version}.`,
    "// Run `npm run tools:schemas` to regenerate. Do not edit by hand.",
    'import type { JsonSchema } from "./json-schema.ts";',
    "",
    `export const BUILTIN_TOOL_SOURCE_VERSION = ${JSON.stringify(version)};`,
    "",
    `export const BUILTIN_TOOL_SCHEMAS: Readonly<Record<string, JsonSchema>> = ${JSON.stringify(tools, null, 2)};`,
    "",
  ].join("\n");
}

// Pure: the same declarations and version always give the same text.
export function generateToolSchemas(source, version, warn = (message) => process.stderr.write(`${message}\n`)) {
  const file = ts.createSourceFile("tool-declarations.d.ts", source, ts.ScriptTarget.Latest, true);
  const inputs = findInterface(file, "BuiltinToolInputs");
  if (inputs === undefined) throw new Error("BuiltinToolInputs is not declared in the tool declarations");
  const tools = {};
  for (const member of inputs.members) {
    const name = ts.isPropertySignature(member) ? nameOf(member.name) : undefined;
    if (name === undefined || member.type === undefined) continue;
    tools[name] = schemaOf(member.type, name, warn);
  }
  const sorted = Object.fromEntries(Object.keys(tools).sort().map((name) => [name, tools[name]]));
  return render(sorted, version);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const version = declarationVersion(readFileSync(versionDeclarations, "utf8"));
  writeFileSync(output, generateToolSchemas(readFileSync(toolDeclarations, "utf8"), version));
  process.stdout.write(`wrote ${output}\n`);
}

export const paths = { toolDeclarations, versionDeclarations, output };
